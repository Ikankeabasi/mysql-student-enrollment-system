# mysql-student-enrollment-system
Student Enrollment Database System

This project is a practical MySQL database system created as part of my cybersecurity and database learning journey.

The project focuses on understanding how databases are structured, managed, and secured using SQL commands and constraints.

Features Implemented

- Database creation
- Table creation
- Data insertion
- Data querying using SELECT
- Updating records with UPDATE
- Constraints and validation
- PRIMARY KEY
- UNIQUE fields
- AUTO_INCREMENT
- DEFAULT values
- CHECK constraints

Skills Practiced

- MySQL
- SQL Queries
- Database Design
- Data Validation
- Debugging SQL Errors
- Command Line SQL Environment

Project Goal

The purpose of this project was to gain hands-on experience with database management and understand how structured data is handled in real-world systems and cybersecurity environments.

